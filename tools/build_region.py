#!/usr/bin/env python3
"""The edition's playable region (the Off the Beaten Track edition: the countries its maps cover), built from
Natural Earth's 1:50m admin-0 countries (public domain, naturalearthdata.com, v5.1.2: the same release as the world
map's layers, maplayers.js).

  python3 tools/build_region.py ne_50m_admin_0_countries.geojson

Writes the same polygons twice, for each side that reads them:
  mod/beamng_earth/lua/ge/extensions/beamngEarth/regiondata.lua   (region.lua: teleports outside are refused)
  server/regiondata.json                                          (region.py: random starts only inside)

Each polygon is its outer ring then its holes (South Africa's hole is Lesotho), every ring a flat list
lat, lon, lat, lon, ... simplified (Douglas-Peucker, TOLERANCE degrees, about 1 km) and rounded to 3 decimals.
An edition with no countries (COUNTRIES empty) writes no polygons: the whole planet stays open.
"""
import json
import os
import sys

NAME = "Off the Beaten Track: Southern Africa"
# ISO 3166-1 alpha-3 (Natural Earth's ADM0_A3); offthebeatentrack.world's covered countries, 2026-10-24
COUNTRIES = ["ZAF", "NAM", "BWA", "ZWE", "ZMB", "MOZ", "LSO", "SWZ", "MWI", "TZA"]
TOLERANCE = 0.01
MIN_RING_POINTS = 4

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LUA_OUT = os.path.join(ROOT, "mod", "beamng_earth", "lua", "ge", "extensions", "beamngEarth", "regiondata.lua")
JSON_OUT = os.path.join(ROOT, "server", "regiondata.json")


def simplify(pts, tol):
    """Douglas-Peucker of [(x, y)] (iterative; the first and last points kept)."""
    if len(pts) < 3:
        return list(pts)
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (ax, ay), (bx, by) = pts[a], pts[b]
        dx, dy = bx - ax, by - ay
        L = (dx * dx + dy * dy) ** 0.5
        best, at = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * (px - ax) - dx * (py - ay)) / L if L > 0 else ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
            if d > best:
                best, at = d, i
        if at >= 0 and best > tol:
            keep[at] = True
            stack += [(a, at), (at, b)]
    return [p for p, k in zip(pts, keep) if k]


def ring_flat(ring):
    """A GeoJSON ring [[lon, lat], ...] -> [lat, lon, ...] simplified and without the closing point, or None."""
    pts = simplify([(float(x), float(y)) for x, y in ring], TOLERANCE)
    if len(pts) > 1 and pts[0] == pts[-1]:
        pts = pts[:-1]
    if len(pts) < MIN_RING_POINTS - 1:
        return None
    out = []
    for lon, lat in pts:
        out += [round(lat, 3), round(lon, 3)]
    return out


def build(geojson):
    polys, names = [], []
    for f in geojson["features"]:
        p = f["properties"]
        iso = p.get("ADM0_A3")
        if iso not in COUNTRIES:
            continue
        names.append((COUNTRIES.index(iso), iso, p.get("NAME")))
        g = f["geometry"]
        parts = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for part in parts:
            rings = [r for r in (ring_flat(r) for r in part) if r]
            if rings:
                polys.append({"country": iso, "rings": rings})
    missing = set(COUNTRIES) - {n[1] for n in names}
    if missing:
        raise SystemExit("not in the file: " + ", ".join(sorted(missing)))
    return {"name": NAME, "countries": [n[2] for n in sorted(names)], "polygons": polys}


def to_lua(data):
    def s(v):
        return json.dumps(v, ensure_ascii=False)
    lines = ["-- Generated by tools/build_region.py from Natural Earth 1:50m countries (public domain). Do not edit.",
             "-- The edition's playable region (region.lua): polygons of rings, each a flat lat, lon, ... list.",
             "return {",
             "  name = " + s(data["name"]) + ",",
             "  countries = { " + ", ".join(s(c) for c in data["countries"]) + " },",
             "  polygons = {"]
    for p in data["polygons"]:
        lines.append("    { country = " + s(p["country"]) + ", rings = {")
        for r in p["rings"]:
            lines.append("      { " + ", ".join(repr(v) for v in r) + " },")
        lines.append("    } },")
    lines += ["  },", "}", ""]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    with open(argv[1], encoding="utf-8") as fh:
        data = build(json.load(fh)) if COUNTRIES else {"name": "", "countries": [], "polygons": []}
    with open(LUA_OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(to_lua(data))
    with open(JSON_OUT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, separators=(",", ":"))
        fh.write("\n")
    n = sum(len(r) // 2 for p in data["polygons"] for r in p["rings"])
    print(f"{len(data['countries'])} countries, {len(data['polygons'])} polygons, {n} points")


if __name__ == "__main__":
    main(sys.argv)
